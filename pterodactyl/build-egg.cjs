#!/usr/bin/env node
/**
 * Builds pterodactyl/egg-quarry-ts.json from the settings below and pterodactyl/install.sh
 * (the egg format wants the script as one escaped string, which nobody wants to edit by hand).
 * Run after changing either:  node pterodactyl/build-egg.cjs
 * "Import Egg" in the Pterodactyl admin area takes the resulting file.
 */
const fs = require("node:fs");
const path = require("node:path");

const variable = (name, description, env_variable, default_value, rules) => ({
  name,
  description,
  env_variable,
  default_value,
  user_viewable: true,
  user_editable: true,
  rules,
  field_type: "text",
});

/** The same variables the server reads (see src/config.ts and src/game/createWorld.ts). */
const variables = [
  variable("Whitelist", "Only listed names and operators may join. Manage names with whitelist add/remove in the console.", "QUARRY_WHITELIST", "false", "required|string|in:true,false"),
  variable("World type", "natural (hills and trees) or flat.", "QUARRY_GENERATOR", "natural", "required|string|in:natural,flat"),
  variable("Seed", "The seed of a natural world. Leave empty for a random one that is made on the first start and then kept. A word works too.", "QUARRY_SEED", "", "nullable|string|max:40"),
  variable("Server list text", "The text under the server name in the multiplayer list.", "QUARRY_MOTD", "A Minecraft server written in TypeScript", "nullable|string|max:100"),
  variable("Maximum players", "How many players can be online at once.", "QUARRY_MAX_PLAYERS", "20", "required|integer|between:1,10000"),
  variable("View distance", "Chunks sent around each player. Lower uses less memory and bandwidth.", "QUARRY_VIEW_DISTANCE", "6", "required|integer|between:2,32"),
  variable("Operators", "Player names that may use operator commands, separated by commas.", "QUARRY_OPS", "", "nullable|string|max:200"),
  variable("Git repository", "Where the server's code is downloaded from when installing.", "GIT_REPO", "https://github.com/StacikM/quarry-ts", "required|string|max:200"),
  variable("Git branch", "The branch to install. Reinstall the server to update it.", "GIT_BRANCH", "main", "required|string|max:100"),
];

const egg = {
  _comment: "DO NOT EDIT: generated by pterodactyl/build-egg.cjs",
  meta: { version: "PTDL_v2", update_url: null },
  exported_at: "2026-10-30T00:00:00+00:00",
  name: "Quarry.ts (Minecraft 1.8.9)",
  author: "146170881+StacikM@users.noreply.github.com",
  description: "A small, low-memory Minecraft 1.8.9 server written in TypeScript. Generated terrain, plugins, a whitelist and moderation commands.",
  features: null,
  docker_images: {
    "Node.js 24": "ghcr.io/parkervcp/yolks:nodejs_24",
    "Node.js 25": "ghcr.io/parkervcp/yolks:nodejs_25",
  },
  file_denylist: [],
  startup: "node dist/index.js",
  config: {
    files: "{}",
    startup: JSON.stringify({ done: "Listening on" }),
    logs: "{}",
    stop: "stop",
  },
  scripts: {
    installation: {
      script: fs.readFileSync(path.join(__dirname, "install.sh"), "utf8").replace(/\r\n/g, "\n"),
      container: "node:24-bookworm",
      entrypoint: "bash",
    },
  },
  variables,
};

if (require.main === module) {
  fs.writeFileSync(path.join(__dirname, "egg-quarry-ts.json"), `${JSON.stringify(egg, null, 4)}\n`);
  console.log("Wrote pterodactyl/egg-quarry-ts.json");
}

module.exports = { egg };
