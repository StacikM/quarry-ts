#!/usr/bin/env node
/**
 * Writes src/world/blastResistance.ts: how well each block withstands explosions (stone 6, obsidian 1200, bedrock 3600000...).
 * The numbers come from the community data set minecraft-data (a dev dependency).
 * Run after changing the Minecraft version:  node scripts/generate-blast-resistance.cjs
 */
const fs = require("node:fs");
const path = require("node:path");
const data = require("minecraft-data")("1.21.11");

const resistant = Object.values(data.blocks)
  .filter((block) => block.resistance > 0)
  .sort((a, b) => a.id - b.id);

const lines = resistant.map((block) => `  ${block.name}: ${block.resistance},`);
const source = `/**
 * GENERATED by scripts/generate-blast-resistance.cjs from minecraft-data (Minecraft 1.21.11). Do not edit by hand.
 * The blast resistance of every block that has any; the others (air, plants, torches...) give no protection at all.
 */
const BLAST_RESISTANCE: Record<string, number> = {
${lines.join("\n")}
};

/** How much of an explosion a block absorbs. \`name\` is the block name without "minecraft:". */
export function blastResistance(name: string): number {
  return Object.hasOwn(BLAST_RESISTANCE, name) ? BLAST_RESISTANCE[name] : 0;
}
`;
fs.writeFileSync(path.join(__dirname, "..", "src", "world", "blastResistance.ts"), source);
console.log(`Wrote src/world/blastResistance.ts (${resistant.length} blocks)`);
