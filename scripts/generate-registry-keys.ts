/**
 * Writes src/protocol/registryKeys.ts: the name of every entry in every
 * registry the 1.21.11 client wants during login (biomes, damage types...).
 *
 * The server only sends the NAMES. The client already has the data for them
 * (they are vanilla, from the "minecraft:core" data pack), so we never have
 * to send the big JSON files.
 *
 * Needs the dev dependency minecraft-data; the result is committed, so the
 * server itself does not depend on it. Run: npx tsx scripts/generate-registry-keys.ts
 */
import fs from "node:fs";
import path from "node:path";
import minecraftData from "minecraft-data";

const login = minecraftData("1.21.11").loginPacket as {
  dimensionCodec: Record<string, { id: string; entries: Array<{ key: string }> }>;
};

const lines: string[] = [
  "// GENERATED by scripts/generate-registry-keys.ts from minecraft-data (Minecraft 1.21.11). Do not edit by hand.",
  "",
  "/** Entry names of each synchronized registry, in the order they are sent (the order gives the numeric IDs). */",
  "export const REGISTRY_KEYS: Record<string, readonly string[]> = {",
];
for (const [registry, { entries }] of Object.entries(login.dimensionCodec)) {
  lines.push(`  ${JSON.stringify(registry)}: ${JSON.stringify(entries.map((entry) => entry.key))},`);
}
lines.push("};", "");
fs.writeFileSync(path.join(__dirname, "..", "src", "protocol", "registryKeys.ts"), lines.join("\n"));
console.log("registries:", Object.keys(login.dimensionCodec).length);
