/** Static Java 1.21.11 collision/support flags, no runtime minecraft-data. */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const data = require('minecraft-data')('1.21.11');
const collision = data.blockCollisionShapes;
const count = Math.max(...data.blocksArray.map(b => b.maxStateId)) + 1;

// Partition the horizontal unit square at every box edge, then check each cell.
// Checking total area or bounding boxes would incorrectly fill holes in hoppers.
function coversTop(boxes) {
  const faces = boxes.filter(b => b[1] < 1 && b[4] >= 1);
  const edges = axis => [...new Set([0, 1, ...faces.flatMap(b => [Math.max(0, Math.min(1, b[axis])), Math.max(0, Math.min(1, b[axis+3]))])])].sort((a,b) => a-b);
  const xs = edges(0), zs = edges(2);
  for (let x=1; x<xs.length; x++) for (let z=1; z<zs.length; z++) {
    const mx=(xs[x-1]+xs[x])/2, mz=(zs[z-1]+zs[z])/2;
    if (!faces.some(b => b[0]<=mx && b[3]>=mx && b[2]<=mz && b[5]>=mz)) return false;
  }
  return true;
}
assert(coversTop([[0,0,0,.5,1,1],[.5,0,0,1,1,1]]));
assert(!coversTop([[0,0,0,.4,1,1],[.6,0,0,1,1,1]]));
const flags = Buffer.alloc(count);
for (const block of data.blocksArray) {
  const shapeIds = collision.blocks[block.name];
  assert(shapeIds !== undefined, `missing collision shape: ${block.name}`);
  if (Array.isArray(shapeIds)) assert.equal(shapeIds.length, block.maxStateId-block.minStateId+1, block.name);
  for (let state=block.minStateId; state<=block.maxStateId; state++) {
    const boxes = collision.shapes[Array.isArray(shapeIds) ? shapeIds[state-block.minStateId] : shapeIds];
    assert(boxes, `missing boxes for ${block.name}:${state}`);
    const full = boxes.length === 1 && boxes[0].every((v,i) => v === (i<3 ? 0 : 1));
    let top = coversTop(boxes);
    // Support shapes differ from collision shapes for these vanilla blocks.
    // Sources: BlockBehaviour#getBlockSupportShape (default collision),
    // LeavesBlock (empty), SnowLayerBlock (layers/8), SoulSandBlock/MudBlock (full block).
    // https://github.com/mahtomedi/minecraft/tree/main/src/main/java/net/minecraft/world/level/block
    if (block.name.endsWith('_leaves')) top = false;
    if (block.name === 'snow') top = state === block.maxStateId;
    if (block.name === 'soul_sand' || block.name === 'mud') top = true;
    flags[state] = Number(full) | (Number(top) << 1);
  }
}
const encoded = flags.toString('base64').match(/.{1,100}/g).map(s=>`  '${s}'`).join(' +\n');
fs.writeFileSync(path.join(__dirname,'../src/world/blockShapes.ts'), `/** Generated by scripts/generate-block-shapes.cjs, minecraft-data 3.109.0 / Java 1.21.11.
 * Flags per state: bit0 = collision is exactly one unit box; bit1 = sturdy UP face.
 * Top coverage uses the union of collision boxes plus explicit vanilla support
 * overrides for leaves, full snow layers, soul sand and mud. Hopper rim has a hole.
 * Static shapes do not model entity/neighbor-dependent collision contexts.
 * No runtime minecraft-data dependency. Retained flag storage: ${count} bytes.
 */
const FLAGS = Buffer.from(
${encoded}, 'base64');
export function isFullCube(state: number): boolean { return ((FLAGS[state] ?? 0) & 1) !== 0; }
export function hasSturdyTop(state: number): boolean { return ((FLAGS[state] ?? 0) & 2) !== 0; }
`);
console.log(`Generated collision/support flags for ${count} states.`);
