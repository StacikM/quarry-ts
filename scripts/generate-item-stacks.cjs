#!/usr/bin/env node
/**
 * Writes src/world/itemStacks.ts: how many of each item fit in one slot, for the items where it is not 64.
 * The numbers come from the community data set minecraft-data (a dev dependency).
 * Run after changing the Minecraft version:  node scripts/generate-item-stacks.cjs
 */
const fs = require("node:fs");
const path = require("node:path");
const data = require("minecraft-data")("1.21.11");

const odd = Object.values(data.items)
  .filter((item) => item.stackSize !== 64)
  .sort((a, b) => a.id - b.id);

const lines = odd.map((item) => `  ${item.name}: ${item.stackSize},`);
const source = `/**
 * GENERATED by scripts/generate-item-stacks.cjs from minecraft-data (Minecraft 1.21.11). Do not edit by hand.
 * The stack size of every item that is not 64.
 */
const STACK_SIZES: Record<string, number> = {
${lines.join("\n")}
};

/** How many of an item fit in one slot. \`name\` is the item name without "minecraft:". */
export function maxStackSize(name: string | undefined): number {
  return (name !== undefined && Object.hasOwn(STACK_SIZES, name) ? STACK_SIZES[name] : undefined) ?? 64;
}
`;
fs.writeFileSync(path.join(__dirname, "..", "src", "world", "itemStacks.ts"), source);
console.log(`Wrote src/world/itemStacks.ts (${odd.length} items that do not stack to 64)`);
