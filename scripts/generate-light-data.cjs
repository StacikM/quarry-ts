/** Development-only generation of Java 1.21.11 state-indexed light tables. */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const data = require('minecraft-data')('1.21.11');
assert.equal(data.version.version, 774);
const blocks = data.blocksArray.slice().sort((a,b) => a.minStateId-b.minStateId);
const count = blocks.at(-1).maxStateId + 1;
function properties(block, state) {
  const props = {};
  let offset = state - block.minStateId;
  for (let i = block.states.length - 1; i >= 0; i--) {
    const p = block.states[i], index = offset % p.num_values;
    props[p.name] = p.values?.[index] ?? (p.type === 'bool' ? String(index === 0) : String(index));
    offset = Math.floor(offset / p.num_values);
  }
  return props;
}
// blocks.json exposes one value per TYPE. Rules below cover common changing states.
// Baseline registrations: https://github.com/mahtomedi/minecraft/blob/main/src/main/java/net/minecraft/world/level/block/Blocks.java
// This is a compatibility light model, not a complete modern face-shape solver.
function lightValues(block, p) {
  const name = block.name;
  let opacity = block.filterLight === 15 ? 255 : block.filterLight;
  let emission = block.emitLight;
  // Lead requested attenuation 3; modern source data has water=1.
  if (name === 'water' || p.waterlogged === 'true') opacity = Math.max(opacity, 3);
  if (p.type === 'double' && name.endsWith('_slab')) opacity = 255;
  const litLevels = { furnace:13, blast_furnace:13, smoker:13, redstone_lamp:15,
    redstone_ore:9, deepslate_redstone_ore:9, redstone_torch:7, redstone_wall_torch:7,
    campfire:15, soul_campfire:10 };
  if (Object.hasOwn(litLevels, name)) emission = p.lit === 'true' ? litLevels[name] : 0;
  if (name === 'light') emission = Number(p.level);
  if (name === 'candle' || name.endsWith('_candle')) emission = p.lit === 'true' ? 3 * Number(p.candles) : 0;
  if (name === 'candle_cake' || name.endsWith('_candle_cake')) emission = p.lit === 'true' ? 3 : 0;
  if (name === 'sea_pickle') emission = p.waterlogged === 'true' ? 3 * Number(p.pickles) + 3 : 0;
  if (name === 'respawn_anchor') emission = [0,3,7,11,15][Number(p.charges)];
  if (name === 'cave_vines' || name === 'cave_vines_plant') emission = p.berries === 'true' ? 14 : 0;
  if (name === 'sculk_sensor' || name === 'calibrated_sculk_sensor') emission = p.sculk_sensor_phase === 'active' ? 1 : 0;
  if (name === 'sculk_catalyst') emission = p.bloom === 'true' ? 6 : 0;
  if (name.endsWith('copper_bulb')) {
    const level = name.includes('oxidized') ? 4 : name.includes('weathered') ? 8 : name.includes('exposed') ? 12 : 15;
    emission = p.lit === 'true' ? level : 0;
  }
  assert(Number.isInteger(opacity) && opacity >= 0 && opacity <= 255, name);
  assert(Number.isInteger(emission) && emission >= 0 && emission <= 15, name);
  return [opacity, emission];
}
const lines = blocks.map(block => {
  const runs = [];
  for (let state = block.minStateId; state <= block.maxStateId; state++) {
    const [opacity, emission] = lightValues(block, properties(block, state));
    const last = runs.at(-1);
    if (last && last[0] === opacity && last[1] === emission) last[2]++;
    else runs.push([opacity, emission, 1]);
  }
  return `  // ${block.name}: states ${block.minStateId}-${block.maxStateId}\n  ${JSON.stringify(runs)},`;
});
const source = `/** Generated by scripts/generate-light-data.cjs for Java 1.21.11.
 * Base: minecraft-data 3.109.0 blocks.json expanded to all ${count} states.
 * Explicit state rules cover lit emitters, candles, berries, anchors and bulbs.
 * Compatibility policy: water/waterlogged states absorb 3 (source data says 1).
 * Full opacity remains 255. Partial-face occlusion is not modeled here.
 * No runtime dependency on minecraft-data or Java.
 */
const OPACITY = new Uint8Array(${count});
const EMISSION = new Uint8Array(${count});
// Decode in a local scope so temporary run arrays can be collected after import.
{
// Per-block runs: [opacity, emission, consecutive state count].
const RUNS: number[][][] = [
${lines.join('\n')}
];
let cursor = 0;
for (const runs of RUNS) for (const [opacity, emission, length] of runs) {
  OPACITY.fill(opacity, cursor, cursor + length);
  EMISSION.fill(emission, cursor, cursor + length);
  cursor += length;
}
}
/** Unknown states are opaque and non-emitting; ids never wrap. */
export function lightOpacity(state: number): number { return OPACITY[state] ?? 255; }
export function lightEmission(state: number): number { return EMISSION[state] ?? 0; }
/** Lookup tables indexed by MODERN STATE ID. */
export const OPACITY_TABLE: Readonly<Uint8Array> = OPACITY;
export const EMISSION_TABLE: Readonly<Uint8Array> = EMISSION;
`;
fs.writeFileSync(path.join(__dirname, '../src/world/lightData.ts'), source);
console.log(`Generated modern light tables for ${count} states (${blocks.length} block types).`);
