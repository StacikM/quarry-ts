/** Refresh src/world/lightData.ts from the independently extracted vanilla registry fixture. */
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const reference = require("../docs/reference/vanilla-1.8.9-light.json");
assert.equal(reference.blocks.length, 198);
reference.blocks.forEach((block, id) => assert.equal(block.id, id));
function rows(key) {
  const result = [];
  for (let start = 0; start < 198; start += 16) {
    const end = Math.min(start + 16, 198);
    result.push("  " + reference.blocks.slice(start, end).map((block) => block[key]).join(", ") + `, // ids ${start}-${end - 1}`);
  }
  return result.join("\n");
}
const source = `/**
 * Minecraft 1.8.9 registry light values for every block id 0-197.
 * Generated by node scripts/generate-light-data.cjs; do not edit table entries by hand.
 * Reference: docs/reference/vanilla-1.8.9-light.json, extracted from the verified
 * Mojang client jar (SHA-1 ${reference.clientSha1}).
 * Unknown ids 198-255 remain opaque and non-emitting; end rods are not a 1.8 block.
 *
 * Opacity is the actual vanilla value (0, 1, 3 or 255), not a visual shape flag.
 * Light loses max(1, opacity) on propagation. Emission ranges from 0 to 15.
 * No runtime dependency on minecraft-data or Java is required.
 */
const OPACITY = new Uint8Array(256).fill(255);
OPACITY.set([
${rows("opacity")}
]);

const EMISSION = new Uint8Array(256);
EMISSION.set([
${rows("emission")}
]);

/** How much light the block removes (0-255). */
export function lightOpacity(blockId: number): number {
  return OPACITY[blockId & 0xff];
}

/** The light level the block gives off (0-15). */
export function lightEmission(blockId: number): number {
  return EMISSION[blockId & 0xff];
}

/** Direct lookup tables for hot loops. Index with the block id (0-255). Do not modify. */
export const OPACITY_TABLE: Readonly<Uint8Array> = OPACITY;
export const EMISSION_TABLE: Readonly<Uint8Array> = EMISSION;
`;
fs.writeFileSync(path.join(root, "src", "world", "lightData.ts"), source);
console.log("Generated complete vanilla 1.8.9 light tables (198 block ids).");
