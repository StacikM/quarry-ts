/** A repeatable random stream returning values in [0, 1). */
export function mulberry32(seed: number): () => number {
  let state = seed | 0;
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let value = Math.imul(state ^ (state >>> 15), state | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
}

/** Hash integer world coordinates independently of generation order. */
export function hash2(seed: number, x: number, z: number): number {
  let value = (seed ^ Math.imul(x, 0x1f123bb5) ^ Math.imul(z, 0x5f356495)) | 0;
  value = Math.imul(value ^ (value >>> 16), 0x7feb352d);
  value = Math.imul(value ^ (value >>> 15), 0x846ca68b);
  return (value ^ (value >>> 16)) | 0;
}
